-- Esquema inicial de la etapa 01-monolito.
--
-- Cada tabla tiene un solo módulo que la escribe (PRD, sección 6). El dueño
-- queda en el comentario de cada tabla: en psql se ve con \dt+.
--
-- Identificadores:
--   - Todas las tablas usan "id" BIGINT como llave primaria.
--   - Las tablas que llena la siembra (cuentas, concursos, problemas,
--     casos_prueba) aceptan id explícito. La siembra usa ids fijos del 1 al 999
--     y hace upsert por id (INSERT ... ON CONFLICT (id) DO UPDATE). Sus
--     secuencias empiezan en 1000, así lo que la aplicación inserte después no
--     choca con la siembra.
--   - envios, leases_evaluacion y resultados no se siembran: el id lo pone
--     siempre la base (GENERATED ALWAYS).
--
-- Una migración aplicada no se edita. Los cambios van en una migración nueva,
-- escrita por el dueño de la tabla (PRD, bitácora 2).

-- Cuentas de demo -----------------------------------------------------------

CREATE TABLE cuentas (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    usuario VARCHAR(50)  NOT NULL,
    nombre  VARCHAR(120) NOT NULL,
    CONSTRAINT cuentas_usuario_unico UNIQUE (usuario)
);

COMMENT ON TABLE cuentas IS
    'Dueño: Inicio de sesión. En 01 solo hay cuentas de demo y las escribe la siembra (excepción temporal, PRD sección 0 punto 2). Leen: Envíos, Tabla de posiciones.';

-- Concursos, problemas y casos ----------------------------------------------

CREATE TABLE concursos (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    inicio TIMESTAMPTZ  NOT NULL,
    fin    TIMESTAMPTZ  NOT NULL,
    estado VARCHAR(20)  NOT NULL DEFAULT 'BORRADOR',
    CONSTRAINT concursos_nombre_unico UNIQUE (nombre),
    CONSTRAINT concursos_ventana_valida CHECK (fin > inicio),
    CONSTRAINT concursos_estado_valido
        CHECK (estado IN ('BORRADOR', 'VERIFICADO', 'ABIERTO', 'CERRADO'))
);

COMMENT ON TABLE concursos IS
    'Dueño: Concursos y problemas. Leen: Envíos, Evaluación, Tabla de posiciones.';

CREATE TABLE problemas (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    concurso_id       BIGINT       NOT NULL REFERENCES concursos (id),
    letra             VARCHAR(1)   NOT NULL,
    titulo            VARCHAR(200) NOT NULL,
    enunciado         TEXT         NOT NULL,
    limite_tiempo_ms  INTEGER      NOT NULL,
    limite_memoria_mb INTEGER      NOT NULL,
    puntos_base       INTEGER      NOT NULL,
    CONSTRAINT problemas_letra_unica_por_concurso UNIQUE (concurso_id, letra),
    CONSTRAINT problemas_letra_valida CHECK (letra ~ '^[A-Z]$'),
    CONSTRAINT problemas_limite_tiempo_positivo CHECK (limite_tiempo_ms > 0),
    CONSTRAINT problemas_limite_memoria_positivo CHECK (limite_memoria_mb > 0),
    CONSTRAINT problemas_puntos_base_no_negativos CHECK (puntos_base >= 0)
);

COMMENT ON TABLE problemas IS
    'Dueño: Concursos y problemas. Leen: Envíos, Evaluación, Tabla de posiciones. El límite de memoria se guarda, pero en 01 no se aplica.';

CREATE TABLE casos_prueba (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    problema_id             BIGINT  NOT NULL REFERENCES problemas (id),
    orden                   INTEGER NOT NULL,
    entrada                 TEXT    NOT NULL,
    salida_esperada         TEXT    NOT NULL,
    en_marcador_provisional BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT casos_prueba_orden_unico_por_problema UNIQUE (problema_id, orden),
    CONSTRAINT casos_prueba_orden_positivo CHECK (orden > 0)
);

COMMENT ON TABLE casos_prueba IS
    'Dueño: Concursos y problemas. Lee: Evaluación. en_marcador_provisional marca el subconjunto de casos del marcador en vivo.';

-- Envíos --------------------------------------------------------------------

CREATE TABLE envios (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_intento  UUID        NOT NULL,
    cuenta_id   BIGINT      NOT NULL REFERENCES cuentas (id),
    problema_id BIGINT      NOT NULL REFERENCES problemas (id),
    lenguaje    VARCHAR(20) NOT NULL,
    codigo      TEXT        NOT NULL,
    llegada_en  TIMESTAMPTZ NOT NULL DEFAULT now(),
    estado      VARCHAR(20) NOT NULL DEFAULT 'RECIBIDO',
    -- Un reintento del mismo intento choca aquí y no crea un segundo envío.
    CONSTRAINT envios_un_envio_por_intento UNIQUE (cuenta_id, id_intento),
    CONSTRAINT envios_lenguaje_valido CHECK (lenguaje IN ('PYTHON3')),
    -- "evaluando" no se guarda: se deriva de un lease vigente (PRD sección 6).
    CONSTRAINT envios_estado_valido CHECK (estado IN ('RECIBIDO', 'EN_COLA'))
);

CREATE INDEX envios_problema_idx ON envios (problema_id);
CREATE INDEX envios_en_cola_idx ON envios (llegada_en) WHERE estado = 'EN_COLA';

COMMENT ON TABLE envios IS
    'Dueño: Envíos. Leen: Evaluación, Tabla de posiciones. llegada_en es la hora del servidor y define el orden de los envíos.';

-- Evaluación ----------------------------------------------------------------

CREATE TABLE leases_evaluacion (
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    envio_id     BIGINT       NOT NULL REFERENCES envios (id),
    worker       VARCHAR(100) NOT NULL,
    tomado_en    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    vence_en     TIMESTAMPTZ  NOT NULL,
    veces_tomado INTEGER      NOT NULL DEFAULT 1,
    -- Un solo lease por envío. Si vence, el worker que lo retoma actualiza
    -- esta misma fila; no se crea otra.
    CONSTRAINT leases_evaluacion_un_lease_por_envio UNIQUE (envio_id),
    CONSTRAINT leases_evaluacion_vencimiento_valido CHECK (vence_en > tomado_en),
    CONSTRAINT leases_evaluacion_veces_tomado_positivo CHECK (veces_tomado > 0)
);

COMMENT ON TABLE leases_evaluacion IS
    'Dueño: Evaluación. Leen: Envíos (deriva "evaluando"), Administración. Vigente si vence_en > now(). Tabla aparte de envios (PRD bitácora 3).';

CREATE TABLE resultados (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    envio_id    BIGINT      NOT NULL REFERENCES envios (id),
    veredicto   VARCHAR(30) NOT NULL,
    tiempo_ms   INTEGER,
    memoria_kb  INTEGER,
    detalle     TEXT,
    evaluado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Un envío reevaluado después de una caída no cuenta dos veces: el
    -- segundo INSERT falla en lugar de sobrescribir (PRD sección 9).
    CONSTRAINT resultados_un_resultado_por_envio UNIQUE (envio_id),
    CONSTRAINT resultados_veredicto_valido CHECK (veredicto IN (
        'ACCEPTED',
        'WRONG_ANSWER',
        'TIME_LIMIT_EXCEEDED',
        'MEMORY_EXCEEDED',
        'ERROR_COMPILACION'
    )),
    CONSTRAINT resultados_tiempo_no_negativo CHECK (tiempo_ms >= 0),
    CONSTRAINT resultados_memoria_no_negativa CHECK (memoria_kb >= 0)
);

COMMENT ON TABLE resultados IS
    'Dueño: Evaluación. Leen: Envíos, Tabla de posiciones. Una fila por envío. memoria_kb queda vacía en 01 (sin límite de memoria). detalle guarda, por ejemplo, el mensaje del error de compilación.';
